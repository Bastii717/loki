#!/bin/sh
# Shared rclone remote setup (sourced by backup.sh and restore.sh).

# MEDIA: the app media bucket (source for backup, target for restore)
export RCLONE_CONFIG_MEDIA_TYPE=s3 RCLONE_CONFIG_MEDIA_PROVIDER="${S3_PROVIDER:-Other}"
export RCLONE_CONFIG_MEDIA_ENDPOINT="$S3_ENDPOINT" RCLONE_CONFIG_MEDIA_REGION="${S3_REGION:-}"
export RCLONE_CONFIG_MEDIA_ACCESS_KEY_ID="$S3_ACCESS_KEY_ID" RCLONE_CONFIG_MEDIA_SECRET_ACCESS_KEY="$S3_SECRET_ACCESS_KEY"
export RCLONE_CONFIG_MEDIA_NO_CHECK_BUCKET=true

# BKP: separate backup bucket with separate credentials; VAULT: crypt remote on top of it
export RCLONE_CONFIG_BKP_TYPE=s3 RCLONE_CONFIG_BKP_PROVIDER="${BACKUP_S3_PROVIDER:-Other}"
export RCLONE_CONFIG_BKP_ENDPOINT="$BACKUP_S3_ENDPOINT" RCLONE_CONFIG_BKP_REGION="${BACKUP_S3_REGION:-}"
export RCLONE_CONFIG_BKP_ACCESS_KEY_ID="$BACKUP_S3_ACCESS_KEY_ID" RCLONE_CONFIG_BKP_SECRET_ACCESS_KEY="$BACKUP_S3_SECRET_ACCESS_KEY"
export RCLONE_CONFIG_BKP_NO_CHECK_BUCKET=true
export RCLONE_CONFIG_VAULT_TYPE=crypt RCLONE_CONFIG_VAULT_REMOTE="BKP:${BACKUP_S3_BUCKET}"
RCLONE_CONFIG_VAULT_PASSWORD="$(rclone obscure "$BACKUP_CRYPT_PASSWORD")"
RCLONE_CONFIG_VAULT_PASSWORD2="$(rclone obscure "$BACKUP_CRYPT_SALT")"
export RCLONE_CONFIG_VAULT_PASSWORD RCLONE_CONFIG_VAULT_PASSWORD2
